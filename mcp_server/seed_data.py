def build_people_and_credits() -> tuple[list[dict[str, Any]], list[tuple[str, str, str | None]]]:
    """Собирает список персон и связки «фильм — персона — роль».

    Режиссёры берутся автоматически из карточек фильмов, остальные персоны —
    из ``PEOPLE`` и ``ACTOR_CREDITS``. Возвращает ``(people, credits)``.
    """
    people: dict[str, dict[str, Any]] = {}

    def add(name: str, role: str, birth_year: int | None = None, country: str | None = None) -> None:
        entry = people.setdefault(
            name, {"name": name, "role": role, "birth_year": birth_year, "country": country}
        )
        if entry["birth_year"] is None and birth_year is not None:
            entry["birth_year"] = birth_year
        if entry["country"] is None and country is not None:
            entry["country"] = country
        if entry["role"] == "director" and role == "director":
            return

    for movie in MOVIES:
        if movie["director"]:
            add(movie["director"], "director")

    for name, role, birth_year, country in PEOPLE:
        add(name, role, birth_year, country)

    credits: list[tuple[str, str, str | None]] = [
        (movie["title"], movie["director"], None)
        for movie in MOVIES
        if movie["director"]
    ]
    credits.extend(ACTOR_CREDITS)
    return list(people.values()), credits


def seed_movies(limit: int = 0) -> list[dict[str, Any]]:
    """Возвращает демо-строки для таблицы ``movies`` (до ``limit``, 0 = все)."""
    return MOVIES[:limit] if limit and limit > 0 else list(MOVIES)
