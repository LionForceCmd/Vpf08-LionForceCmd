def legacy_plan_prompt() -> str:
    """Промпт для моделей без native function calling."""
    return f"{SYSTEM_PROMPT}\n\n{LEGACY_PLAN_INSTRUCTION}"


def format_tool_call_log(tool_name: str, arguments: dict[str, Any] | None = None) -> str:
    """Короткая строка для логов: какие инструменты бот вызвал."""
    if not arguments:
        return tool_name
    try:
        rendered = json.dumps(arguments, ensure_ascii=False, sort_keys=True)
    except (TypeError, ValueError):
        rendered = str(arguments)
    if len(rendered) > 160:
        rendered = rendered[:157] + "..."
    return f"{tool_name}({rendered})"
